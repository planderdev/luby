    function splitWords(el) {
        if (el.dataset.splitReady === 'true') return;
        var text = el.textContent.trim();
        if (!text) return;
        el.setAttribute('aria-label', text);
        el.innerHTML = text.split(/\s+/).map(function (word) {
            var className = hasCjk(word) ? 'split-word is-cjk' : 'split-word';
            return '<span class="' + className + '" aria-hidden="true"><span>' + word + '</span></span>';
        }).join(' ');
        el.dataset.splitReady = 'true';
    }

    function splitChars(el) {
        if (el.dataset.splitReady === 'true') return;
        var text = el.textContent;
        if (!text.trim()) return;
        el.setAttribute('aria-label', text.trim());
        el.innerHTML = Array.prototype.map.call(text, function (char) {
            var className = hasCjk(char) ? 'split-char is-cjk' : 'split-char';
            return char === ' '
                ? '<span aria-hidden="true"> </span>'
                : '<span class="' + className + '" aria-hidden="true">' + char + '</span>';
        }).join('');
        el.dataset.splitReady = 'true';
    }

    function splitGraphemes(text) {
        if (window.Intl && window.Intl.Segmenter) {
            var segmenter = new Intl.Segmenter(document.documentElement.lang || 'ko', { granularity: 'grapheme' });
            return Array.from(segmenter.segment(text), function (part) {
                return part.segment;
            });
        }
        return Array.from(text);
    }

    function hasCjk(text) {
        return /[\u3400-\u4DBF\u4E00-\u9FFF\uF900-\uFAFF]/.test(text);
    }

    function isTrailingMark(text) {
        return /^[,.;:!?%…，。！？、；：）)\]}]+$/.test(text);
    }

    function isKoreanParticle(text) {
        return /^(?:은|는|이|가|을|를|으로|로|과|와|도|만|부터|까지|에서|에게|께|의|에|처럼|보다|마다|밖에|조차|마저|나|이나|라도|이라도|든지|인지|라고|이라고)[,.;:!?%…，。！？、；：）)\]}]*$/.test(text);
    }

    function splitTypeTokens(text) {
        if (/\s/.test(text)) {
            return (text.match(/\S+|\s+/g) || []).map(function (segment) {
                return {
                    type: /^\s+$/.test(segment) ? 'space' : 'word',
                    text: segment
                };
            });
        }

        if (window.Intl && window.Intl.Segmenter) {
            var segmenter = new Intl.Segmenter(document.documentElement.lang || 'ko', { granularity: 'word' });
            return Array.from(segmenter.segment(text), function (part) {
                return {
                    type: part.segment.trim() ? 'word' : 'space',
                    text: part.segment
                };
            }).reduce(function (tokens, token) {
                var previous = tokens[tokens.length - 1];
                if ((isTrailingMark(token.text) || isKoreanParticle(token.text)) && previous && previous.type === 'word') {
                    previous.text += token.text;
                } else {
                    tokens.push(token);
                }
                return tokens;
            }, []);
        }

        return [{ type: 'word', text: text }];
    }

    function splitTypeLine(el) {
        if (el.dataset.typeReady === 'true') return;
        var parts = Array.prototype.map.call(el.childNodes, function (node) {
            if (node.nodeType === Node.ELEMENT_NODE && node.tagName === 'BR') {
                return { type: 'break', text: '\n' };
            }

            return { type: 'text', text: node.textContent || '' };
        }).filter(function (part) {
            return part.type === 'break' || part.text;
        });
        var text = parts.length ? parts.map(function (part) { return part.text; }).join('') : el.textContent;
        if (!text.trim()) return;

        el.textContent = '';
        el.dataset.typeReady = 'true';
        el.setAttribute('aria-label', text.trim());
        el.setAttribute('role', 'text');

        function appendTypedText(value) {
            splitTypeTokens(value).forEach(function (token) {
                if (token.type === 'space') {
                    var space = document.createElement('span');
                    space.className = 'type-space';
                    space.setAttribute('aria-hidden', 'true');
                    space.textContent = ' ';
                    el.appendChild(space);
                    return;
                }

                var word = document.createElement('span');
                word.className = hasCjk(token.text) ? 'type-word is-cjk' : 'type-word';
                word.setAttribute('aria-hidden', 'true');
                splitGraphemes(token.text).forEach(function (char) {
                    var span = document.createElement('span');
                    span.className = hasCjk(char) ? 'type-char is-cjk' : 'type-char';
                    span.textContent = char;
                    word.appendChild(span);
                });
                el.appendChild(word);
            });
        }

        parts.forEach(function (part) {
            if (part.type === 'break') {
                el.appendChild(document.createElement('br'));
                return;
            }

            appendTypedText(part.text);
        });
    }

